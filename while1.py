i = 5 # объявление переменной i для условия цикла
while i < 10: # лучше дать осмысленное имя!
    # ключевое слово 'while' и условие выполнение цикла
    # тело цикла
    print(i) # вывод значения переменной i
    a = int(input("a?"))
    if a % 2 == 0:
        i -= 1 # увеличение значения переменной i на единицу
    else:
        i += 1
    
